"""Production Baseline Security promotion: VALIDATION -> PRODUCTION (H.1).

## What this module is, and is not

This is the ONLY path by which a `worker_baseline_security_certificates`
row is ever written into the PRODUCTION database. It never runs the
Baseline Security evaluation harness itself (`security.evaluation`/
`security.live_certification` own that), never talks to a model, and
never accepts a client-supplied outcome, evidence_ref, certificate id,
digest, or fingerprint. It re-verifies an EXISTING `PASS` VALIDATION
certificate against the current live runtime and current durable
evidence, then durably carries that verdict forward into PRODUCTION by
calling `workers.security_baseline.record_baseline_certificate()` — the
same low-level recorder every other certificate path already uses. This
module never inserts into `worker_baseline_security_certificates`
directly and never duplicates that function's validation; it is not a
parallel authority path.

Promotion is role-independent, exactly like Baseline Security itself:
this module never reads, writes, or reasons about a Planner (or any
other role) certificate, and never touches `worker_trust_events` or
`permission_grants`. A promoted PRODUCTION Baseline Security certificate
is one of several INDEPENDENT inputs `workers.production_eligibility`
later combines (never merges) with a role certificate — promotion alone
grants no trust, no permission, and no role certificate to anyone.

## Fail-closed re-verification, not a copy

A VALIDATION `PASS` certificate is durable evidence of what a runtime
did *at evaluation time*. Promotion never assumes that is still true; it
independently re-establishes every fact production eligibility itself
would require, using the SAME machinery that already enforces it:

1. the live Ollama runtime is re-probed right now
   (`security.live_certification.verify_ollama_runtime`) against the
   server-owned, config-derived `expected` — a changed digest or
   runtime version since the VALIDATION run fails closed here, before
   any certificate is even looked up.
2. the CURRENT common runtime identity is rebuilt from that verified
   probe (`workers.security_baseline.runtime_profile_identity_from_config`)
   and must recompute to exactly `expected.expected_runtime_identity_fingerprint`
   — a stale or mismatching identity fails closed.
3. the most recent VALIDATION certificate whose OWN recorded runtime
   identity exactly `.matches()` that current identity is selected —
   never merely "the latest certificate for this worker" — mirroring
   `workers.production_eligibility`'s own no-wildcard binding. A newer,
   non-matching, or non-`PASS` certificate for the same profile is never
   silently skipped in favor of an older one.
4. that certificate must be `PASS` under the CURRENT `BASELINE_VERSION`
   — `FAIL`, `HARD_DISQUALIFIED`, or a policy-stale `PASS` all fail
   closed.
5. its durable evidence is reread and reverified
   (`security.evidence.read_baseline_security_evidence`) — missing,
   wrong-kind, hash-mismatched, or tampered evidence fails closed before
   anything is copied or recorded.
6. the live runtime is re-probed a SECOND time immediately before the
   write, closing the gap between evidence verification and the
   PRODUCTION write itself — mirrors `live_certification.
   certify_live_baseline_security`'s own pre-record re-probe.

Only once every one of those holds is the evidence document's exact
bytes copied into the PRODUCTION content store (content-addressed, so
the copy is independently re-verifiable from PRODUCTION alone) and
`record_baseline_certificate()` called against the PRODUCTION connection
with that SAME evidence_ref and the freshly-verified runtime profile.

## Idempotent, not duplicating

Certificates are append-only everywhere else in this codebase (see
`workers.security_baseline`'s own docstring), but "append-only" must
never mean "a repeated identical promotion mints a second, independent
authority row." Before writing anything, this module checks whether a
PRODUCTION certificate already exists whose
`promoted_from_validation_certificate_id` equals the EXACT VALIDATION
certificate's own `certificate_id` (schema v17) — not a comparison of
runtime identity or evidence content, a direct provenance link to the
one specific, already-durable VALIDATION row this promotion attempt
re-verified. That `certificate_id` is itself server-owned: it was
generated by `record_baseline_certificate()` when the VALIDATION
certificate was originally recorded (by the live certification path),
never supplied by a client. If a PRODUCTION certificate already claims
that exact provenance, it is returned as an idempotent success
(`ok=True`, `reason="already_promoted_to_production"`) and no new row,
no evidence copy, and no new audit event is created. This never
invalidates or overwrites a historical certificate, and never treats a
merely similar-looking prior promotion as the same authority. A
genuinely different, independently-issued VALIDATION certificate —
even one evaluated against the identical runtime — has its own,
different `certificate_id` and is therefore promoted as a normal new
row, exactly like any other re-certification.

Why provenance-by-certificate-id rather than a broader
`(worker_id, runtime_identity_fingerprint, evidence_ref)` uniqueness
invariant (an earlier revision of this module used exactly that): a
uniqueness invariant spanning ordinary columns constrains EVERY row in
`worker_baseline_security_certificates`, including plain VALIDATION
certificates that were never promoted and were never meant to be
constrained at all — VALIDATION recording has always been free to
create as many rows sharing a runtime identity and even, in principle,
identical evidence as evaluation produces, and neither the database
schema nor `record_baseline_certificate()` has ever forbidden that. A
broad invariant there would (a) risk failing a schema upgrade against
any database that already happens to hold duplicate historical triples
and (b) silently narrow VALIDATION semantics that H.1 was never asked
to change. `promoted_from_validation_certificate_id` sidesteps both:
it is `NULL` on every certificate this module did not itself write
(every VALIDATION certificate, and every historical row from before
this column existed), so a partial UNIQUE index on it — non-`NULL`
values only — constrains EXCLUSIVELY the rows this module produces,
touches no other row, and cannot fail against pre-existing data. See
migration 0017's own docstring for the schema-level detail.

The pre-check above alone is a sequential read-then-write guard: it is
what short-circuits the common case (a repeated or retried promotion
request) cheaply, before doing any further live probe or evidence
work, but by itself it cannot serialize two TRULY concurrent requests
that both read "not yet promoted" before either has written anything.
The actual safety guarantee against that race is the schema-level
partial UNIQUE index itself, not an application-level lock this module
manages. Once two concurrent requests both reach `record_baseline_
certificate()`'s own `BEGIN IMMEDIATE` write transaction, SQLite's
write lock already serializes their two INSERT attempts against each
other; the index is what makes the SECOND of those two serialized
attempts fail with `sqlite3.IntegrityError` instead of silently
succeeding as a duplicate authority row for the same VALIDATION
provenance. This module catches exactly that failure, re-reads the row
the other request just committed (by the same provenance lookup), and
returns it as the same `already_promoted_to_production` idempotent
success — never an unhandled error, and never a second audit event. No
database write lock is ever held across an Ollama network probe or
evidence verification: every such step happens before `record_
baseline_certificate()` is called, and that function's own transaction
is already the shortest possible atomic section (just the INSERT and
its audit event).

## No client-supplied authority

Every value this module reasons about — `expected` (server-owned config,
never HTTP input; see `BaselineCertificationTarget`), the VALIDATION
certificate, and the reread evidence document — is either backend-owned
configuration or durable evidence this module itself re-verifies. The
WebUI action that triggers this accepts `worker_id` only as a resource
path (identifying WHICH already-registered worker to promote, exactly
like every other Certification Center route) and an empty JSON body —
no outcome, evidence_ref, certificate_id, digest, or fingerprint is ever
a caller-supplied parameter here.
"""

