@dataclass(frozen=True)
class ProductionPromotionResult:
    """Bounded result of one promotion attempt. Never carries raw model
    text, secrets, or HTTP bodies — mirrors `LiveSecurityCertificationResult`."""

    ok: bool
    reason: str
    runtime_identity_fingerprint: str | None = None
    validation_certificate_id: str | None = None
    production_certificate_id: str | None = None
    evidence_ref: str | None = None


def _deny(reason: str, **kwargs) -> ProductionPromotionResult:
    return ProductionPromotionResult(False, reason, **kwargs)


def _latest_matching_certificate(certificates, runtime_profile: RuntimeProfileIdentity):
    """The first (most recent, by the repo's own `issued_at DESC` order)
    certificate whose OWN recorded runtime identity exactly `.matches()`
    `runtime_profile` — never a wildcard, never "any certificate for this
    worker." Mirrors `workers.production_eligibility`'s own matching
    helper exactly (that helper is module-private there; this is the
    same rule, not a divergent reimplementation)."""
    for certificate in certificates:
        stored = runtime_profile_binding_from_stored(
            model_tag=certificate.model_tag,
            model_digest=certificate.model_digest,
            endpoint=certificate.endpoint,
            runtime_version=certificate.runtime_version,
            normalizer_id=certificate.normalizer_id,
            normalizer_version=certificate.normalizer_version,
            runtime_config_fingerprint=certificate.runtime_config_fingerprint,
            runtime_identity_fingerprint=certificate.runtime_identity_fingerprint,
        )
        if stored.matches(runtime_profile):
            return certificate
    return None


@dataclass(frozen=True)
class PromotionAvailability:
    """Backend-authoritative, durable-state-only projection of whether
    promotion would currently succeed. See `describe_promotion_availability`.
    Never carries raw model text, secrets, or HTTP bodies."""

    available: bool
    reason: str
    runtime_identity_fingerprint: str | None = None
    validation_certificate_id: str | None = None
    production_certificate_id: str | None = None


def describe_promotion_availability(
    validation_conn: sqlite3.Connection,
    production_conn: sqlite3.Connection,
    *,
    worker_id: str,
    expected: LiveOllamaRuntimeExpectation,
) -> PromotionAvailability:
    """The ONE backend-authoritative source the WebUI reads to decide
    whether to offer the promotion action. This is a DISPLAY projection
    only, computed entirely from already-durable state and the
    server-owned expected config -- it never probes live Ollama (GET
    routes in this codebase never make a live network call; mirrors
    `CertificationService._runtime_status`'s and `_baseline_status`'s
    own "config-bound, not live-probed" precedent). Consequently a
    `True` here is advisory, not a guarantee: `promote_baseline_
    security_to_production()` independently re-verifies everything live
    and remains the only authoritative decision -- exactly the same
    relationship `ready_for_certification` already has to an actual
    certification run.

    Reason vocabulary intentionally matches `promote_baseline_security_
    to_production()`'s own deny reasons (`no_validation_certificate`,
    `validation_certificate_not_pass`, `already_promoted_to_production`,
    ...) so a frontend or operator never has to learn two vocabularies
    for the same underlying gate. The frontend MUST treat this as the
    sole source of promotability -- it must never independently infer
    availability from `baseline_security.status`, run/busy state, or any
    other client-side heuristic.

    Unlike `promote_baseline_security_to_production()`, this does not
    require a VALIDATION `workers` row to already exist (that row is a
    lazy mirror of PRODUCTION registration -- see `CertificationService.
    _ensure_validation_worker` -- created on first preflight/run, not a
    read-time side effect this display projection should ever perform).
    A worker that is PRODUCTION-registered but has never had a
    VALIDATION run naturally has no certificates, which already reports
    `no_validation_certificate` below -- exactly mirroring `_baseline_
    status`'s own precedent of querying certificates directly rather
    than gating on that row."""
    if WorkersRepo(production_conn).get(worker_id) is None:
        return PromotionAvailability(False, "unknown_worker")

    try:
        runtime_profile = runtime_profile_identity_from_config(
            model_tag=expected.model_tag,
            model_digest=expected.model_digest,
            endpoint=expected.openai_base_url,
            runtime_version=expected.runtime_version,
            effective_context_tokens=expected.effective_context_tokens,
            temperature=float(expected.temperature),
            normalizer_id=expected.normalizer_id,
            normalizer_version=expected.normalizer_version,
        )
    except (TypeError, ValueError):
        return PromotionAvailability(False, "insufficient_runtime_profile_identity")

    fingerprint = runtime_profile.runtime_identity_fingerprint
    if fingerprint != expected.expected_runtime_identity_fingerprint:
        return PromotionAvailability(
            False, "runtime_identity_fingerprint_mismatch",
            runtime_identity_fingerprint=fingerprint,
        )

    certificates = BaselineSecurityCertificatesRepo(validation_conn).list_for_worker(worker_id)
    if not certificates:
        return PromotionAvailability(
            False, "no_validation_certificate", runtime_identity_fingerprint=fingerprint,
        )
    certificate = _latest_matching_certificate(certificates, runtime_profile)
    if certificate is None:
        return PromotionAvailability(
            False, "validation_certificate_profile_mismatch",
            runtime_identity_fingerprint=fingerprint,
        )
    if certificate.baseline_version != BASELINE_VERSION:
        return PromotionAvailability(
            False, "validation_certificate_baseline_version_stale",
            runtime_identity_fingerprint=fingerprint,
            validation_certificate_id=certificate.certificate_id,
        )
    if certificate.outcome != SecurityBaselineOutcome.PASS.value:
        return PromotionAvailability(
            False, "validation_certificate_not_pass",
            runtime_identity_fingerprint=fingerprint,
            validation_certificate_id=certificate.certificate_id,
        )

    already_promoted = BaselineSecurityCertificatesRepo(
        production_conn,
    ).get_by_promotion_provenance(certificate.certificate_id)
    if already_promoted is not None:
        return PromotionAvailability(
            False, "already_promoted_to_production",
            runtime_identity_fingerprint=fingerprint,
            validation_certificate_id=certificate.certificate_id,
            production_certificate_id=already_promoted.certificate_id,
        )

    return PromotionAvailability(
        True, "promotable",
        runtime_identity_fingerprint=fingerprint,
        validation_certificate_id=certificate.certificate_id,
    )


def promote_baseline_security_to_production(
    validation_conn: sqlite3.Connection,
    production_conn: sqlite3.Connection,
    *,
    worker_id: str,
    validation_blobs_dir: Path | str,
    production_blobs_dir: Path | str,
    expected: LiveOllamaRuntimeExpectation,
    now_fn=utcnow_iso,
) -> ProductionPromotionResult:
    """Re-verify and durably carry forward one `PASS` VALIDATION Baseline
    Security certificate into PRODUCTION. See the module docstring for
    the complete, ordered fail-closed check list. Never mutates
    `worker_trust_events`, `permission_grants`, or any role-certificate
    table; never records more than one new PRODUCTION
    `worker_baseline_security_certificates` row per distinct VALIDATION
    `certificate_id` -- a repeat promotion of the exact same VALIDATION
    certificate returns the existing row instead (see "Idempotent, not
    duplicating").
    """
    if not isinstance(worker_id, str) or not worker_id:
        return _deny("malformed_promotion_request")
    if not isinstance(expected, LiveOllamaRuntimeExpectation):
        return _deny("malformed_promotion_request")
    if (
        not isinstance(validation_blobs_dir, (str, Path))
        or not str(validation_blobs_dir).strip()
        or not isinstance(production_blobs_dir, (str, Path))
        or not str(production_blobs_dir).strip()
    ):
        return _deny("missing_durable_security_evidence")
    if WorkersRepo(production_conn).get(worker_id) is None:
        return _deny("unknown_worker")
    if WorkersRepo(validation_conn).get(worker_id) is None:
        return _deny("unknown_worker")

    try:
        runtime_version, model_digest = verify_ollama_runtime(expected)
    except ValueError as exc:
        reason = str(exc) if str(exc) else "runtime_probe_unavailable"
        return _deny(reason)

    try:
        runtime_profile = runtime_profile_identity_from_config(
            model_tag=expected.model_tag,
            model_digest=model_digest,
            endpoint=expected.openai_base_url,
            runtime_version=runtime_version,
            effective_context_tokens=expected.effective_context_tokens,
            temperature=float(expected.temperature),
            normalizer_id=expected.normalizer_id,
            normalizer_version=expected.normalizer_version,
        )
    except (TypeError, ValueError):
        return _deny("insufficient_runtime_profile_identity")

    fingerprint = runtime_profile.runtime_identity_fingerprint
    if fingerprint != expected.expected_runtime_identity_fingerprint:
        return _deny(
            "runtime_identity_fingerprint_mismatch",
            runtime_identity_fingerprint=fingerprint,
        )

    certificates = BaselineSecurityCertificatesRepo(validation_conn).list_for_worker(worker_id)
    if not certificates:
        return _deny(
            "no_validation_certificate",
            runtime_identity_fingerprint=fingerprint,
        )
    certificate = _latest_matching_certificate(certificates, runtime_profile)
    if certificate is None:
        return _deny(
            "validation_certificate_profile_mismatch",
            runtime_identity_fingerprint=fingerprint,
        )
    if certificate.baseline_version != BASELINE_VERSION:
        return _deny(
            "validation_certificate_baseline_version_stale",
            runtime_identity_fingerprint=fingerprint,
            validation_certificate_id=certificate.certificate_id,
        )
    if certificate.outcome != SecurityBaselineOutcome.PASS.value:
        return _deny(
            "validation_certificate_not_pass",
            runtime_identity_fingerprint=fingerprint,
            validation_certificate_id=certificate.certificate_id,
        )

    # Idempotency: a PRODUCTION certificate already recorded with this
    # EXACT VALIDATION certificate as its provenance is the same
    # authority this request would otherwise mint again. Return it
    # as-is; write nothing new. See the module docstring's "Idempotent,
    # not duplicating".
    already_promoted = BaselineSecurityCertificatesRepo(
        production_conn,
    ).get_by_promotion_provenance(certificate.certificate_id)
    if already_promoted is not None:
        return ProductionPromotionResult(
            True,
            "already_promoted_to_production",
            runtime_identity_fingerprint=fingerprint,
            validation_certificate_id=certificate.certificate_id,
            production_certificate_id=already_promoted.certificate_id,
            evidence_ref=already_promoted.evidence_ref,
        )

    try:
        document = read_baseline_security_evidence(
            validation_conn,
            validation_blobs_dir,
            certificate.evidence_ref,
            expected_runtime_identity_fingerprint=fingerprint,
        )
    except SecurityEvaluationEvidenceError as exc:
        return _deny(
            exc.reason,
            runtime_identity_fingerprint=fingerprint,
            validation_certificate_id=certificate.certificate_id,
        )
    if document.get("worker_id") != worker_id:
        return _deny(
            "evidence_worker_mismatch",
            runtime_identity_fingerprint=fingerprint,
            validation_certificate_id=certificate.certificate_id,
        )

    # Close the gap between evidence verification and the PRODUCTION
    # write: re-probe live Ollama once more, mirroring
    # `live_certification.certify_live_baseline_security`'s own
    # pre-record re-probe.
    try:
        verify_ollama_runtime(expected)
    except ValueError:
        return _deny(
            "runtime_changed_since_validation",
            runtime_identity_fingerprint=fingerprint,
            validation_certificate_id=certificate.certificate_id,
        )

    try:
        validation_store = ContentStore(validation_conn, validation_blobs_dir)
        evidence_bytes = validation_store.read(certificate.evidence_ref)
    except KeyError:
        return _deny(
            "missing_durable_security_evidence",
            runtime_identity_fingerprint=fingerprint,
            validation_certificate_id=certificate.certificate_id,
        )

    production_store = ContentStore(production_conn, production_blobs_dir)
    copied = production_store.put(
        evidence_bytes,
        media_type="application/json",
        source_kind=EVIDENCE_KIND,
        exportable=False,
    )
    if copied.content_hash != certificate.evidence_ref:
        return _deny(
            "durable_security_evidence_hash_mismatch",
            runtime_identity_fingerprint=fingerprint,
            validation_certificate_id=certificate.certificate_id,
        )

    # Reread and reverify from PRODUCTION alone -- the copy must be
    # independently trustworthy from the PRODUCTION side, not merely
    # byte-identical at write time.
    try:
        read_baseline_security_evidence(
            production_conn,
            production_blobs_dir,
            certificate.evidence_ref,
            expected_runtime_identity_fingerprint=fingerprint,
        )
    except SecurityEvaluationEvidenceError as exc:
        return _deny(
            exc.reason,
            runtime_identity_fingerprint=fingerprint,
            validation_certificate_id=certificate.certificate_id,
            evidence_ref=certificate.evidence_ref,
        )

    # Final atomic section: the sequential check above already handles
    # the common case (a repeated, non-concurrent promotion request),
    # but two TRULY concurrent requests can both pass it before either
    # has written anything. `record_baseline_certificate()` opens its
    # own short `BEGIN IMMEDIATE` write transaction for exactly the
    # INSERT (+ audit event) below -- no network probe or evidence
    # verification ever runs while that lock is held; all of that
    # already happened above. SQLite's write lock alone already
    # serializes two concurrent INSERT attempts against each other; the
    # `ux_worker_baseline_security_certificates_promotion_provenance`
    # partial unique index (schema v17) is what makes the SECOND of
    # those two serialized attempts fail deterministically instead of
    # silently succeeding as a duplicate authority row -- see that
    # migration's own docstring. A failure here is resolved to the row
    # the OTHER concurrent request just committed, never treated as an
    # unexplained error.
    try:
        recorded = record_baseline_certificate(
            production_conn,
            worker_id=worker_id,
            runtime_profile=runtime_profile,
            outcome=SecurityBaselineOutcome.PASS,
            evidence_ref=certificate.evidence_ref,
            reason="promoted_from_validation",
            hard_disqualifiers=(),
            now_fn=now_fn,
            promoted_from_validation_certificate_id=certificate.certificate_id,
        )
    except sqlite3.IntegrityError:
        winner = BaselineSecurityCertificatesRepo(
            production_conn,
        ).get_by_promotion_provenance(certificate.certificate_id)
        if winner is None:
            # The partial unique index exists on exactly this one
            # column; a violation that does NOT resolve to a matching
            # row here is not this invariant and must never be
            # silently absorbed.
            raise
        return ProductionPromotionResult(
            True,
            "already_promoted_to_production",
            runtime_identity_fingerprint=fingerprint,
            validation_certificate_id=certificate.certificate_id,
            production_certificate_id=winner.certificate_id,
            evidence_ref=winner.evidence_ref,
        )
    if not recorded.ok or recorded.certificate is None:
        return _deny(
            recorded.reason,
            runtime_identity_fingerprint=fingerprint,
            validation_certificate_id=certificate.certificate_id,
            evidence_ref=certificate.evidence_ref,
        )

    AuditWriter(production_conn).append(
        task_id=None,
        event_type=EventType.SECURITY_BASELINE_CERTIFICATE_PROMOTED_TO_PRODUCTION,
        actor_type="system",
        actor_id=worker_id,
        payload={
            "worker_id": worker_id,
            "validation_certificate_id": certificate.certificate_id,
            "production_certificate_id": recorded.certificate.certificate_id,
            "runtime_identity_fingerprint": fingerprint,
            "evidence_ref": certificate.evidence_ref,
        },
    )

    return ProductionPromotionResult(
        True,
        "promoted_to_production",
        runtime_identity_fingerprint=fingerprint,
        validation_certificate_id=certificate.certificate_id,
        production_certificate_id=recorded.certificate.certificate_id,
        evidence_ref=certificate.evidence_ref,
    )
